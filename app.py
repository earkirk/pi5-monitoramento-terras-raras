import streamlit as st
import ee
import json

# Configuração da página do Streamlit
st.set_page_config(layout="wide", page_title="Monitoramento de Terras Raras - FATEC")

st.title("🌱 Sistema Autónomo de Monitorização Ambiental - Terras Raras")
st.write("Pipeline Geoespacial integrando Google Earth Engine, Sentinel-2 e Random Forest.")

# 0. INICIALIZAÇÃO DO EARTH ENGINE VIA SERVICE ACCOUNT
@st.cache_resource
def initialize_gee():
    try:
        with open("credentials.json") as f:
            secret_data = json.load(f)

        service_account = secret_data["client_email"]
        credentials = ee.ServiceAccountCredentials(service_account, "credentials.json")

        ee.Initialize(credentials, project='pi5-fatec-507412')
        return True
    except Exception as e:
        st.error(f"Erro ao autenticar no Earth Engine: {e}")
        return False

if initialize_gee():
    st.sidebar.header("Parâmetros da Área de Estudo")

    lat = st.sidebar.number_input("Latitude", value=-19.6660, format="%.4f")
    lon = st.sidebar.number_input("Longitude", value=-46.9351, format="%.4f")
    buffer_val = st.sidebar.slider("Raio de Buffer (metros)", min_value=500, max_value=5000, value=2500, step=500)

    if st.sidebar.button("Executar Análise de Impacto"):
        with st.spinner("Processando imagens e gerando visualizações no Google Earth Engine (Sentinel-2)..."):

            # 1. DEFINIÇÃO DA ÁREA
            roi = ee.Geometry.Point([lon, lat]).buffer(buffer_val)

            # 2. CARREGAR IMAGEM SENTINEL-2
            colecao = ee.ImageCollection('COPERNICUS/S2_SR_HARMONIZED') \
                .filterBounds(roi) \
                .filterDate('2023-01-01', '2023-12-31')

            colecao_filtrada = colecao.filter(ee.Filter.lt('CLOUDY_PIXEL_PERCENTAGE', 30))

            imagem_padrao = ee.Image(ee.Algorithms.If(
                colecao_filtrada.size().gt(0),
                colecao_filtrada.median(),
                colecao.sort('CLOUDY_PIXEL_PERCENTAGE').first()
            ))

            imagem = imagem_padrao.clip(roi)

            # 3. CÁLCULO DE ÍNDICES ESPECTRAIS
            ndvi = imagem.normalizedDifference(['B8', 'B4']).rename('NDVI')
            ndwi = imagem.normalizedDifference(['B3', 'B8']).rename('NDWI')
            swir = imagem.select('B11').rename('SWIR')

            imagem_completa = imagem.addBands([ndvi, ndwi, swir])

            # 4. ROTULAGEM AUTÓNOMA RESTRITA
            mascara_autonoma = ee.Image(0) \
                .where(ndvi.lte(0.12).And(swir.gte(2500)).And(ndwi.lt(-0.05)), 0) \
                .where(ndvi.gte(0.22).Or(ndwi.gte(-0.05)), 1) \
                .rename('classe_autonoma')

            # 5. AMOSTRAGEM ESTRATIFICADA
            amostras_autonomas = imagem_completa.addBands(mascara_autonoma).stratifiedSample(
                numPoints=200,
                classBand='classe_autonoma',
                region=roi,
                scale=10,
                geometries=True
            )

            amostras_com_rand = amostras_autonomas.randomColumn('random')
            dados_treino = amostras_com_rand.filter(ee.Filter.lt('random', 0.7))
            dados_teste = amostras_com_rand.filter(ee.Filter.gte('random', 0.7))

            # 6. TREINO DO RANDOM FOREST
            bandas = ['B2', 'B3', 'B4', 'B8', 'B11', 'NDVI']
            classificador = ee.Classifier.smileRandomForest(30).train(
                features=dados_treino,
                classProperty='classe_autonoma',
                inputProperties=bandas
            )

            imagem_classificada = imagem_completa.select(bandas).classify(classificador)

            # 6.1 MÁSCARA PÓS-CLASSIFICAÇÃO (ÁGUA)
            mascara_agua_rigorosa = ndwi.gte(-0.05)
            imagem_classificada = imagem_classificada.where(mascara_agua_rigorosa, 1)

            # 7. CÁLCULO DE ACURÁCIA
            validacao = dados_teste.classify(classificador)
            matriz_confusao = validacao.errorMatrix('classe_autonoma', 'classification')

            acuracia_geral = matriz_confusao.accuracy().getInfo() * 100
            indice_kappa = matriz_confusao.kappa().getInfo()

            # 8. CÁLCULO DE ÁREA IMPACTADA
            area_mina = imagem_classificada.eq(0).multiply(ee.Image.pixelArea())
            estatisticas = area_mina.reduceRegion(
                reducer=ee.Reducer.sum(),
                geometry=roi,
                scale=10,
                maxPixels=1e9
            )

            area_m2 = estatisticas.getNumber('classification').getInfo() if estatisticas.get('classification') else 0
            area_ha = area_m2 / 10000
            area_km2 = area_m2 / 1000000

            # 9. EXIBIÇÃO DOS RESULTADOS EM CARDS ANALÍTICOS
            st.success("Análise geoespacial concluída com sucesso!")

            col1, col2, col3, col4 = st.columns(4)
            col1.metric("Acurácia Geral", f"{acuracia_geral:.2f}%")
            col2.metric("Índice Kappa", f"{indice_kappa:.4f}")
            col3.metric("Área Impactada", f"{area_ha:.2f} ha")
            col4.metric("Área em km²", f"{area_km2:.4f} km²")

            # 10. EXIBIÇÃO DAS IMAGENS (RGB E NDVI) LADO A LADO
            st.markdown("---")
            st.subheader("🛰️ Inspeção Visual da Área de Estudo")

            col_img1, col_img2 = st.columns(2)

            with col_img1:
                st.markdown("**Composição Sentinel-2 (RGB)**")
                try:
                    vis_rgb = {
                        'bands': ['B4', 'B3', 'B2'],
                        'min': 0,
                        'max': 3000,
                        'dimensions': 600
                    }
                    url_rgb = imagem.getThumbURL(vis_rgb)
                    st.image(url_rgb, caption="Satélite Natural (RGB)", use_container_width=True)
                except Exception as e:
                    st.error(f"Erro ao carregar RGB: {e}")

            with col_img2:
                st.markdown("**Índice de Vegetação (NDVI)**")
                try:
                    vis_ndvi = {
                        'min': -0.2,
                        'max': 0.8,
                        'palette': ['blue', 'white', 'yellow', 'green'],
                        'dimensions': 600
                    }
                    url_ndvi = ndvi.getThumbURL(vis_ndvi)
                    st.image(url_ndvi, caption="NDVI (Saúde da Vegetação)", use_container_width=True)
                except Exception as e:
                    st.error(f"Erro ao carregar NDVI: {e}")

            # 11. OPÇÃO DE ACESSO AO CODE EDITOR NA NUVEM
            st.markdown("---")
            st.link_button(
                "🚀 Abrir Ambiente no Google Earth Engine Code Editor",
                "https://code.earthengine.google.com/"
            )